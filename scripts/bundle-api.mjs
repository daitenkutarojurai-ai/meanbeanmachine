// Bundles the multiplayer server into api/ws.js for Vercel: one plain ES module with
// the engine and `ws` inlined, so the Function needs no install or TypeScript step.
import { build } from 'esbuild';

await build({
  entryPoints: ['apps/server/src/vercel.ts'],
  outfile: 'api/ws.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  // ws optionally requires these native speedups and falls back without them.
  external: ['bufferutil', 'utf-8-validate'],
  banner: {
    js: "// Generated by scripts/bundle-api.mjs from apps/server/src. Do not edit.\nimport { createRequire } from 'node:module';\nconst require = createRequire(import.meta.url);",
  },
  legalComments: 'none',
  logLevel: 'warning',
});
